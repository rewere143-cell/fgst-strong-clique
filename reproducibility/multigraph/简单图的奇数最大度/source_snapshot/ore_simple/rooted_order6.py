#!/usr/bin/env python3
"""Order-6 marked-root extension LP and optional PSD cutting planes.
Uses the exact orbit index generated by enumerate_order6.cpp.
Numerical output is experimental, never itself a proof certificate.
"""
import sys,itertools as it,json,time
from pathlib import Path
import numpy as np
from scipy.sparse import csr_matrix,vstack,save_npz,load_npz,hstack
from scipy.optimize import linprog
from rooted_order4 import pairs,matrix,encode
from rooted_order5 import build as build5
BASE=Path(__file__).parent
ORDER_SIX_INDEX=BASE.parent/'reproducibility/data/order6_orbit_index.bin'

def build(gram=True):
 t=time.time();p=build5();N5=len(p['variables']);reps6=json.loads((BASE/'order6_representatives.json').read_text());idx6=np.fromfile(ORDER_SIX_INDEX,dtype=np.int32);N=N5+len(reps6)
 pairs6=pairs(6);powers=[3**j for j in range(14)];pos6={e:i for i,e in enumerate(pairs6)}
 def code6(c):return sum(int(v)*q for v,q in zip(c[1:],powers))
 def ix(n,c):
  if n<6:return p['ix'](n,c)
  q=int(idx6[code6(c)]);return N5+q if q>=0 else None
 def allowed(n,c):return (n==6 and idx6[code6(c)]>=0) or (n<6 and c in p['data'][n][2])
 variables=p['variables']+[(6,(2,)+tuple((c//q)%3 for q in powers))for c in reps6]
 rows=[];names=[]
 extvalues=[]
 for ext in it.product(range(3),repeat=5):
  delta=sum(ext[u]*powers[pos6[u,5]-1]for u in range(5));extvalues.append((ext,delta))
 for c in p['data'][5][1]:
  base=sum(v*powers[pos6[u,vv]-1]for (u,vv),v in zip(pairs(5)[1:],c[1:]));neighbors=[{}for _ in range(5)]
  for ext,delta in extvalues:
   j=int(idx6[base+delta])
   if j<0:continue
   for u in range(5):
    if ext[u]:neighbors[u][N5+j]=neighbors[u].get(N5+j,0)+1
  for u,row in enumerate(neighbors):
   row[ix(5,c)]=-1;rows.append(row);names.append(f'degree_5_{c}_{u}')
 ri=[];ci=[];vv=[]
 for i,row in enumerate(rows):
  for j,v in row.items():ri.append(i);ci.append(j);vv.append(v)
 A6=csr_matrix((vv,(ri,ci)),shape=(len(rows),N));A=vstack([hstack([p['A'],csr_matrix((p['A'].shape[0],N-N5))]),A6],format='csr');rhs=np.r_[p['rhs'],np.zeros(len(rows))];obj=np.r_[p['obj'],np.zeros(N-N5)];names=p['names']+names
 blocks=[(typ,m,K,hstack([D,csr_matrix((D.shape[0],N-N5))],format='csr'))for typ,m,K,D in p['blocks']]
 if gram:
  # Each type is considered only up to complete relabeling, including root
  # relabeling to another marked edge, which preserves the root-average measure.
  requests=[(2,(2,),[2,3,4])]+[(4,c,[4,5])for c in p['data'][4][1]]
  for k,typ,sizes in requests:
   flags=[]
   for n in sizes:
    if n==k:flags.append((n,typ));continue
    fs=p['data'][n][0]
    seen=set()
    for c in fs:
     a=matrix(c,n)
     if encode(a,list(range(k)))!=typ:continue
     canon=min(encode(a,list(range(k))+list(perm))for perm in it.permutations(range(k,n)))
     if canon not in seen:seen.add(canon);flags.append((n,canon))
   m=len(flags);K=np.zeros((m,m));entries={}
   for i,(ni,c) in enumerate(flags):
    ai=matrix(c,ni)
    for j in range(i,m):
     nj,d=flags[j];aj=matrix(d,nj);n=ni+nj-k
     if n==2:K[i,j]=K[j,i]=1;continue
     a=np.zeros((n,n),dtype=int);a[:ni,:ni]=ai
     perm=list(range(k))+list(range(ni,n))
     for u,v in pairs(nj):a[perm[u],perm[v]]=a[perm[v],perm[u]]=aj[u,v]
     cross=list(it.product(range(k,ni),range(ni,n)));row={}
     for cs in it.product(range(3),repeat=len(cross)):
      for (u,v),z in zip(cross,cs):a[u,v]=a[v,u]=z
      h=encode(a,list(range(n)))
      if allowed(n,h):q=ix(n,h);row[q]=row.get(q,0)+1
     for q,val in row.items():
      entries[i*m+j,q]=val
      if i!=j:entries[j*m+i,q]=val
   rr=[];cc=[];vv=[]
   for (r,c),v in entries.items():rr.append(r);cc.append(c);vv.append(v)
   D=csr_matrix((vv,(rr,cc)),shape=(m*m,N));blocks.append((typ,m,K,D))
  print('built',len(blocks),'blocks',sum(b[3].nnz for b in blocks),'gram nonzeros',flush=True)
 print('order6 variables',N,'degree equations',len(rhs),'build seconds',time.time()-t,flush=True)
 return dict(variables=variables,A=A,rhs=rhs,obj=obj,names=names,blocks=blocks)

def solve(psd=False,maxiter=200):
 t=time.time();p=build(gram=psd);Aeq=p['A'];beq=p['rhs'];N=Aeq.shape[1];A=csr_matrix((0,N));b=np.array([]);cuts=[];history=[]
 if psd and '--resume' in sys.argv and (BASE/'order6_psd_result.json').exists():
  old=json.loads((BASE/'order6_psd_result.json').read_text());cuts=old['cuts']
  if '--cut-limit' in sys.argv:cuts=cuts[:int(sys.argv[sys.argv.index('--cut-limit')+1])]
  cr=[];cb=[]
  for cut in cuts:
   typ,m,K,D=p['blocks'][cut['block']];v=np.array(cut['vector']);cr.append(csr_matrix(-(np.outer(v,v).reshape(-1)@D)));cb.append(v@K@v)
  A=vstack(cr,format='csr');b=np.array(cb)
  print('resumed valid PSD cuts',len(cuts),flush=True)
 for step in range(maxiter if psd else 1):
  r=linprog(-p['obj'],A_ub=A if A.shape[0]else None,b_ub=b if len(b)else None,A_eq=Aeq,b_eq=beq,bounds=(0,None),method='highs-ipm',options={'time_limit':300})
  if not r.success:raise RuntimeError(r.message)
  used_cuts=len(cuts);mineig=0;new=[]
  for j,(typ,m,K,D) in enumerate(p['blocks']):
   M=K+(D@r.x).reshape(m,m);w,V=np.linalg.eigh(M);mineig=min(mineig,float(w.min()))
   for h in np.flatnonzero(w < -1e-7):
    v=V[:,h];outer=np.outer(v,v).reshape(-1);row=csr_matrix(-(outer@D));new.append((row,v@K@v));cuts.append({'block':j,'vector':v.tolist()})
  history.append({'iteration':step,'objective':float(-r.fun),'min_eig':mineig,'cuts_added':len(new)})
  print(f'{step:3d} c={-r.fun:.12g} min_eig={mineig:.3g} cuts={len(new)} elapsed={time.time()-t:.1f}s',flush=True)
  suffix='psd' if psd else 'lp';np.savez(BASE/f'order6_{suffix}_primal.npz',x=r.x)
  snapshot={'objective':float(-r.fun),'gram_min_eigenvalue':mineig,'variables':N,'linear_constraints':len(beq),'history':history,'status':r.message,'degree_duals':dict((n,float(v))for n,v in zip(p['names'],r.eqlin.marginals)if abs(v)>1e-10),'cuts':cuts,'used_cuts':used_cuts,'cut_duals':r.ineqlin.marginals.tolist()}
  (BASE/f'order6_{suffix}_result.json').write_text(json.dumps(snapshot,indent=2)+'\n')
  if not psd or not new:break
  A=vstack([A]+[x[0]for x in new],format='csr');b=np.r_[b,[x[1]for x in new]]
 return p,r,snapshot
if __name__=='__main__':solve('--psd'in sys.argv,maxiter=1 if '--once' in sys.argv else 200)
